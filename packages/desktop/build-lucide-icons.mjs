// Generate renderer/lucide-icons.mjs from the pinned `lucide` devDependency.
//
//   npm run icons:lucide            (from packages/desktop) — rewrite the module
//   npm run icons:lucide -- --check — verify it matches the pinned package
//
// The renderer never imports npm code at runtime for icons: the generated
// module is plain, reviewable data (element name + attribute pairs) for only
// the icons the app names, with the Lucide ISC notice. The Redesign v3 HTML
// states its glyphs are placeholders for Lucide.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const TARGET = join(HERE, 'renderer', 'lucide-icons.mjs');
/** The only Lucide icons the app uses (kebab-case Lucide names). */
export const LUCIDE_NAMES = Object.freeze([
  'book-open', 'brain', 'check', 'chevron-down', 'chevron-left', 'chevron-right', 'circle-alert', 'circle-dot', 'clock',
  'columns-2', 'contrast', 'ellipsis', 'external-link', 'file-text', 'folder-git-2', 'git-branch', 'git-pull-request', 'house',
  'info', 'keyboard', 'laptop', 'list-checks', 'mail', 'maximize-2', 'minus', 'package', 'panel-left', 'play', 'plus', 'refresh-cw', 'rotate-ccw', 'rows-2',
  'search', 'sliders-horizontal', 'sparkles', 'square', 'square-terminal', 'square-x', 'terminal', 'trash-2',
  'triangle-alert', 'x',
]);
const pascal = name => name.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('');
const ALLOWED_TAGS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ALLOWED_ATTRS = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points']);

export async function generate() {
  const lucide = await import('lucide');
  const require = createRequire(import.meta.url);
  const pkg = JSON.parse(readFileSync(join(dirname(require.resolve('lucide/package.json')), 'package.json'), 'utf8'));
  const icons = {};
  for (const name of LUCIDE_NAMES) {
    const node = lucide[pascal(name)];
    if (!Array.isArray(node)) throw new Error(`lucide has no icon ${name}`);
    icons[name] = node.map(([tag, attrs]) => {
      if (!ALLOWED_TAGS.has(tag)) throw new Error(`${name}: unexpected element ${tag}`);
      const pairs = Object.entries(attrs).filter(([key]) => key !== 'key');
      for (const [key, value] of pairs) if (!ALLOWED_ATTRS.has(key) || !/^[-0-9a-zA-Z .,]*$/.test(value)) throw new Error(`${name}: unexpected ${key}`);
      return [tag, pairs];
    });
  }
  const body = JSON.stringify(icons, null, 0).replace(/\],"/g, '],\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, '\n}');
  return `// GENERATED by build-lucide-icons.mjs from lucide@${pkg.version} — do not edit.\n` +
    `// Regenerate: cd packages/desktop && npm run icons:lucide\n//\n` +
    `// Lucide icons: ISC License, Copyright (c) 2026 Lucide Icons and Contributors.\n` +
    `// Portions derived from Feather (MIT, Copyright (c) 2013-2023 Cole Bemis).\n` +
    `// Each icon is a 24x24 stroke icon: [element, [[attribute, value], ...]][].\n` +
    `export const LUCIDE_VERSION = ${JSON.stringify(pkg.version)};\n` +
    `export const LUCIDE_ICONS = Object.freeze(${body});\n`;
}

async function main(argv) {
  const source = await generate();
  if (argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8') !== source) { console.error('renderer/lucide-icons.mjs does not match the pinned lucide package'); process.exitCode = 1; }
    else console.log('renderer/lucide-icons.mjs matches the pinned lucide package');
    return;
  }
  writeFileSync(TARGET, source);
  console.log(`wrote ${LUCIDE_NAMES.length} Lucide icons to renderer/lucide-icons.mjs`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main(process.argv.slice(2));
